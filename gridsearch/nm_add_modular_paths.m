function added = nm_add_modular_paths(rootDir)
% nm_add_modular_paths
% Add the shallow non-package NMModular directory tree to the MATLAB path.
%
% Usage:
%   nm_add_modular_paths();
%   nm_add_modular_paths('/path/to/NMModular');
%
% The directory layout is intentionally non-packaged at this stage.  This
% helper keeps path setup explicit while avoiding root-level wrapper/alias
% functions for the individual modules.

if nargin < 1 || isempty(rootDir)
    rootDir = fileparts(mfilename('fullpath'));
end
rootDir = char(rootDir);
subdirs = { ...
    '.', ...
    'core', ...
    'bridge', ...
    'ui', ...
    'dataio', ...
    fullfile('dataio','data_import'), ...
    'preproc', ...
    fullfile('preproc','subconfigs'), ...
    'ml', ...
    'scaffold', ...
    'examples', ...
    'tests'};
added = {};
for i = 1:numel(subdirs)
    p = fullfile(rootDir, subdirs{i});
    if exist(p, 'dir') == 7
        addpath(p);
        added{end+1} = p; %#ok<AGROW>
    end
end
end
