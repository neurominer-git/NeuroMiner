        function diagnostic = diagnostic(severity, code, source, message, identityField, ME)
            % diagnostic  Build one explicit diagnostic with optional exception stack.
            if nargin < 1 || isempty(severity), severity = 'info'; end
            if nargin < 2, code = ''; end
            if nargin < 3, source = ''; end
            if nargin < 4, message = ''; end
            if nargin < 5, identityField = ''; end
            if nargin < 6, ME = []; end
            diagnostic = NMImagingContractTools.diagnosticTemplate();
            diagnostic.severity = char(string(severity));
            diagnostic.code = char(string(code));
            diagnostic.source = char(string(source));
            diagnostic.message = char(string(message));
            diagnostic.identityField = char(string(identityField));
            if isa(ME,'MException')
                diagnostic.exceptionIdentifier = char(string(ME.identifier));
                stackRows = cell(1,numel(ME.stack));
                for ii = 1:numel(ME.stack)
                    stackRows{ii} = sprintf('%s:%d', ME.stack(ii).name, ME.stack(ii).line);
                end
                diagnostic.stack = stackRows;
            end
        end

        function policy = normalizeDisplayGridPolicy(value)
            % normalizeDisplayGridPolicy  Validate the accepted display-grid policy.
            policy = lower(strtrim(char(string(value))));
            if isempty(policy), policy = 'structural_reference'; end
            allowed = {'structural_reference','feature_reference'};
            if ~any(strcmp(policy,allowed))
                error('NMImagingContractTools:InvalidDisplayGridPolicy', ...
                    'Unsupported imaging display-grid policy "%s". Supported policies are structural_reference and feature_reference.', policy);
            end
        end

        function id = stableId(varargin)
            % stableId  Create a deterministic FNV-1a identity from scalar metadata.
            pieces = cell(1,nargin);
            for ii = 1:nargin
                pieces{ii} = NMImagingContractTools.scalarIdentityText(varargin{ii});
            end
            txt = strjoin(pieces,'|');
            bytes = uint8(txt);
            h = uint32(2166136261);
            prime = uint64(16777619);
            modulus = uint64(4294967296);
            for ii = 1:numel(bytes)
                h = bitxor(h,uint32(bytes(ii)));
                h = uint32(mod(uint64(h)*prime,modulus));
            end
            id = lower(dec2hex(h,8));
        end
    end

    methods (Static, Access = private)
        function txt = scalarIdentityText(value)
            if isempty(value)
                txt = '';
            elseif ischar(value)
                txt = value;
            elseif isstring(value) && isscalar(value)
                txt = char(value);
            elseif isnumeric(value) || islogical(value)
                txt = mat2str(double(value));
            else
                error('NMImagingContractTools:NonScalarIdentityValue', ...
                    'Stable imaging identities accept only empty, text, numeric, or logical metadata values.');
            end
        end
