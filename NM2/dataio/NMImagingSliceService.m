classdef NMImagingSliceService
% NMImagingSliceService
% -------------------------------------------------------------------------
% Numeric orthogonal-slice extraction and plane geometry for the imaging viewer. The
% service returns matrices and explicit voxel mappings; it does not map
% colours or render browser/report graphics.
%
% Documentation: docs/NMImagingSliceContract.md
% -------------------------------------------------------------------------

    methods (Static)
        function slice = extract(volume, planeId, sliceIndex)
            % extract  Extract one affine-aware anatomical/native display plane.
            NMImagingVolumeAccess.validateVolume(volume);
            planeId = lower(strtrim(char(string(planeId))));
            convention = NMImagingSliceService.planeConvention(volume.spatialReference);
            planeIndex = find(strcmp({convention.planes.planeId},planeId),1,'first');
            if isempty(planeIndex)
                error('NMImagingSliceService:UnsupportedPlane', ...
                    'Unsupported orthogonal plane "%s".',planeId);
            end
            plane = convention.planes(planeIndex);
            sliceIndex = NMImagingSliceService.validateSlice(sliceIndex,plane.maxSlice,planeId);
            order = [plane.verticalVoxelAxis plane.horizontalVoxelAxis plane.normalVoxelAxis];
            oriented = permute(volume.data,order);
            data = oriented(:,:,sliceIndex);
            if plane.verticalDirection < 0, data = flipud(data); end
            if plane.horizontalDirection < 0, data = fliplr(data); end
            pixelToVoxel = NMImagingSliceService.pixelMappingMatrix( ...
                double(volume.dimensions),plane,sliceIndex);
            slice = struct( ...
                'schema','NMImagingNumericSlice', ...
                'schemaVersion',1, ...
                'planeId',planeId, ...
                'sliceIndex',double(sliceIndex), ...
                'maxSlice',double(plane.maxSlice), ...
                'data',data, ...
                'dimensions',double(size(data)), ...
                'pixelToVoxel',pixelToVoxel, ...
                'rowAxis',sprintf('voxel_axis_%d_direction_%+d',plane.verticalVoxelAxis,plane.verticalDirection), ...
                'columnAxis',sprintf('voxel_axis_%d_direction_%+d',plane.horizontalVoxelAxis,plane.horizontalDirection), ...
                'flippedRows',logical(plane.verticalDirection < 0), ...
                'gridId',volume.gridId);
        end

        function convention = planeConvention(reference)
            % planeConvention  Resolve anatomical planes from the display affine.
            %
            % Cardinal affines may permute or reverse voxel axes. Plane names are
            % therefore derived from world axes rather than assumed to be I/J/K.
            % Oblique grids remain explicit native planes and are never labelled
            % as anatomical axial/coronal/sagittal planes.
            reference = NMImagingSpatialReference.fromVolume(reference);
            dims = double(reference.dimensions);
            planeTemplate = struct( ...
                'planeId','', ...
                'displayLabel','', ...
                'conventionMode','', ...
                'normalVoxelAxis',0, ...
                'horizontalVoxelAxis',0, ...
                'verticalVoxelAxis',0, ...
                'horizontalDirection',0, ...
                'verticalDirection',0, ...
                'width',0, ...
                'height',0, ...
                'maxSlice',0, ...
                'orientationLabels',struct('left','','right','','top','','bottom',''), ...
                'sliceDirectionLabels',struct('low','','high',''));
            planes = repmat(planeTemplate,1,3);
            if reference.isOblique
                mode = 'native_oblique';
                native = { ...
                    'axial','Native K plane',3,2,1,1,1; ...
                    'coronal','Native J plane',2,1,3,1,-1; ...
                    'sagittal','Native I plane',1,2,3,1,-1};
                for ii=1:3
                    planes(ii) = NMImagingSliceService.makePlane( ...
                        native{ii,1},native{ii,2},mode,native{ii,3},native{ii,4}, ...
                        native{ii,5},native{ii,6},native{ii,7},dims, ...
                        NMImagingSliceService.nativeOrientationLabels( ...
                            native{ii,4},native{ii,6},native{ii,5},native{ii,7}), ...
                        NMImagingSliceService.nativeSliceLabels(native{ii,3}));
                end
            else
                mode = 'world_cardinal';
                axesWorld = double(reference.axisUnitVectors);
                [~,voxelForWorld] = max(abs(axesWorld),[],2);
                if numel(unique(voxelForWorld)) ~= 3
                    error('NMImagingSliceService:AmbiguousCardinalAxes', ...
                        'The image orientation does not define an unambiguous left-right, anterior-posterior and inferior-superior display. Check the image orientation information.');
                end
                signs = zeros(1,3);
                for ww=1:3
                    signs(ww) = sign(axesWorld(ww,voxelForWorld(ww)));
                    if signs(ww) == 0
                        error('NMImagingSliceService:InvalidCardinalAxis', ...
                            'The image orientation contains an invalid zero direction. Check the image header/orientation information.');
                    end
                end
                % Screen conventions: R is right in axial/coronal views; A is
                % top in axial, S is top in coronal/sagittal, and A is left in
                % sagittal. Orientation letters make the convention explicit.
                planes(1) = NMImagingSliceService.makePlane('axial','Axial',mode, ...
                    voxelForWorld(3),voxelForWorld(1),voxelForWorld(2), ...
                    signs(1),-signs(2),dims, ...
                    struct('left','L','right','R','top','A','bottom','P'), ...
                    NMImagingSliceService.sliceLabels(signs(3),'I','S'));
                planes(2) = NMImagingSliceService.makePlane('coronal','Coronal',mode, ...
                    voxelForWorld(2),voxelForWorld(1),voxelForWorld(3), ...
                    signs(1),-signs(3),dims, ...
                    struct('left','L','right','R','top','S','bottom','I'), ...
                    NMImagingSliceService.sliceLabels(signs(2),'P','A'));
                planes(3) = NMImagingSliceService.makePlane('sagittal','Sagittal',mode, ...
                    voxelForWorld(1),voxelForWorld(2),voxelForWorld(3), ...
                    -signs(2),-signs(3),dims, ...
                    struct('left','A','right','P','top','S','bottom','I'), ...
                    NMImagingSliceService.sliceLabels(signs(1),'L','R'));
            end
            convention = struct( ...
                'schema','NMImagingPlaneConvention', ...
                'schemaVersion',1, ...
                'mode',mode, ...
                'coordinateConvention','spm_one_based_direct', ...
                'gridId',reference.gridId, ...
                'planes',planes);
        end

        function voxel = pixelToVoxel(slice, column, row)
            % pixelToVoxel  Map one 1-based displayed pixel to direct SPM voxel.
            if ~isstruct(slice) || ~isscalar(slice) || ~isfield(slice,'pixelToVoxel')
                error('NMImagingSliceService:InvalidSlice','The prepared slice information is invalid. Run Preview again; if the problem persists, check the image header and spatial reference.');
            end
            if ~isscalar(column) || ~isscalar(row) || ~isfinite(column) || ~isfinite(row)
                error('NMImagingSliceService:InvalidPixel','Pixel column and row must be finite scalars.');
            end
            mapped = slice.pixelToVoxel * [double(column);double(row);0;1];
            voxel = mapped(1:3)';
        end
    end

    methods (Static, Access = private)
        function plane = makePlane(planeId,displayLabel,mode,normalAxis,horizontalAxis,verticalAxis, ...
                horizontalDirection,verticalDirection,dims,orientationLabels,sliceDirectionLabels)
            plane = struct( ...
                'planeId',char(string(planeId)), ...
                'displayLabel',char(string(displayLabel)), ...
                'conventionMode',char(string(mode)), ...
                'normalVoxelAxis',double(normalAxis), ...
                'horizontalVoxelAxis',double(horizontalAxis), ...
                'verticalVoxelAxis',double(verticalAxis), ...
                'horizontalDirection',double(horizontalDirection), ...
                'verticalDirection',double(verticalDirection), ...
                'width',double(dims(horizontalAxis)), ...
                'height',double(dims(verticalAxis)), ...
                'maxSlice',double(dims(normalAxis)), ...
                'orientationLabels',orientationLabels, ...
                'sliceDirectionLabels',sliceDirectionLabels);
        end

        function labels = sliceLabels(axisSign,negativeLabel,positiveLabel)
            if axisSign > 0
                labels = struct('low',negativeLabel,'high',positiveLabel);
            else
                labels = struct('low',positiveLabel,'high',negativeLabel);
            end
        end

        function labels = nativeOrientationLabels(horizontalAxis,horizontalDirection,verticalAxis,verticalDirection)
            horizontalLetter = char(double('I')+double(horizontalAxis)-1);
            verticalLetter = char(double('I')+double(verticalAxis)-1);
            if horizontalDirection > 0
                left = ['-' horizontalLetter]; right = ['+' horizontalLetter];
            else
                left = ['+' horizontalLetter]; right = ['-' horizontalLetter];
            end
            if verticalDirection > 0
                top = ['-' verticalLetter]; bottom = ['+' verticalLetter];
            else
                top = ['+' verticalLetter]; bottom = ['-' verticalLetter];
            end
            labels = struct('left',left,'right',right,'top',top,'bottom',bottom);
        end

        function labels = nativeSliceLabels(normalAxis)
            letter = char(double('I')+double(normalAxis)-1);
            labels = struct('low',['-' letter],'high',['+' letter]);
        end

        function mapping = pixelMappingMatrix(dims,plane,sliceIndex)
            mapping = zeros(4,4);
            mapping(4,4) = 1;
            if plane.horizontalDirection > 0
                mapping(plane.horizontalVoxelAxis,1) = 1;
            else
                mapping(plane.horizontalVoxelAxis,1) = -1;
                mapping(plane.horizontalVoxelAxis,4) = dims(plane.horizontalVoxelAxis)+1;
            end
            if plane.verticalDirection > 0
                mapping(plane.verticalVoxelAxis,2) = 1;
            else
                mapping(plane.verticalVoxelAxis,2) = -1;
                mapping(plane.verticalVoxelAxis,4) = dims(plane.verticalVoxelAxis)+1;
            end
            mapping(plane.normalVoxelAxis,4) = double(sliceIndex);
        end

        function value = validateSlice(value,maxValue,planeId)
            if ~isscalar(value) || ~isnumeric(value) || ~isfinite(value)
                error('NMImagingSliceService:InvalidSlice', ...
                    '%s slice index must be one finite numeric scalar.',planeId);
            end
            value = round(double(value));
            if value < 1 || value > maxValue
                error('NMImagingSliceService:SliceOutOfBounds', ...
                    '%s slice index %d is outside 1..%d.',planeId,value,maxValue);
            end
        end
    end
end
