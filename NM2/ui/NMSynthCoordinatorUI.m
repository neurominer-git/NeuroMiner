        function copyAssets(webDir)
            src=fileparts(mfilename('fullpath'));
            names={'NMTrainTemplateUI.css','NMResultsViewerUI.css','NMModuleNavigationRail.css', ...
                'NMModuleNavigationRail.js','NMModuleIconSet.js', ...
                'NMModal.js','NMModal.css','NMRuntimeProgressViewer.js', ...
                'NMRuntimeProgressViewer.css','NMRuntimeJobClient.js', ...
                'NMSynthCoordinatorUI_main.js'};
            for i=1:numel(names)
                copyfile(fullfile(src,names{i}),fullfile(webDir,names{i}),'f');
            end
        end

