classdef NMSynthCoordinatorUI
% Workbench child page for existing-data and fully synthetic SYNTH.
% Generation, training and performance remain owned by NMSynthTools,
% NMSimulationTools and NMSynthPerformanceTools.
    methods (Static)
        function paths = export(NM,outDir,ctx)
            % Opening the coordinator reads persisted NM metadata only.
            % Child artifacts are reconciled by Resume/Reconstruct/Refresh.
            dirs=NMUISessionTools.resolve(outDir,ctx,'nm_synth_coordinator_ui');
            NMDataIOUI.saveSessionNM(NM,dirs.tmpDir);
            state=NMSynthCoordinatorUI.stateFromNM(NM,ctx);
            stateJson=NMConfigTools.writeJsonAliases({fullfile(dirs.tmpDir,'synth_coordinator_state.json')}, ...
                state,'SYNTH coordinator state');
            NMSynthCoordinatorUI.copyAssets(dirs.webDir);
            NMSynthCoordinatorUI.writeTextFile(fullfile(dirs.webDir,'nm_synth_coordinator.html'), ...
                NMSynthCoordinatorUI.htmlTextFromJson(stateJson));
            NMPreprocUI.writeBridge(fullfile(dirs.pyDir,'nm_bridge_server.py'));
            paths=struct('root',dirs.root,'webRoot',dirs.webRoot,'webDir',dirs.webDir, ...
                'tmpDir',dirs.tmpDir,'html',fullfile(dirs.webDir,'nm_synth_coordinator.html'), ...
                'entryHtml','nm_synth_coordinator.html','entryHtmlPath',fullfile(dirs.webDir,'nm_synth_coordinator.html'));
        end

        function state = stateFromNM(NM,ctx)
            synth=NMSynthCoordinatorUI.experimentGeneratorState( ...
                NMSynthTools.stateFromNM(NM));
            observedN=0;
            % nm2-allow: NMDataIOAPITools.emptyNM has no label before the first DataIO import.
            if isfield(NM,'label'), observedN=size(NM.label,1);end
            defs=NMStatusGuardTools.defsState(NM);
            ready=defs.import_finished && ...
                NMDataIOBrowserModeTools.committedModalityCount(NM)>0;
            % Fully synthetic modality validation is deferred until that tab is selected.
            % Opening the coordinator never probes data representation or feature counts.
            % nm2-allow: Only dedicated SYNTH placeholder templates carry this marker.
            placeholder=isfield(NM,'SYNTH') && isfield(NM.SYNTH,'fullySyntheticDefinition');
            state=struct('page','synth_coordinator', ...
                'observedN',observedN,'existingDataReady',observedN>0 && ready && ~placeholder, ...
                'fullySyntheticReady',ready, ...
                'synth',synth, ...
                'modeflag',NMAlternativeLabelTools.effectiveMode(NM), ...
                'experiments',{NMSynthCoordinatorUI.experimentCatalogue(NM)}, ...
                'defaultOutputDir',fullfile(pwd,'SYNTH_Experiments'));
            state=NMUISessionTools.attachAppContextToState(ctx,state,'synth_coordinator');
        end

        function synth = experimentGeneratorState(synth)
            % Coordinator-only selection projection; do not rewrite the generic
            % TrainParam.SYNTH generator or historical experiment records.
            if ismember(synth.synthMethod,[1 2]), synth.synthMethod=3; end
        end

        function experiments = experimentCatalogue(NM)
            % JSON arrays must retain their shape for 0, 1 or N experiments.
            experiments=cell(1,0);
            % First-use SYNTH is optional in observed workspaces.
            % nm2-allow: Persisted NM predating SYNTH has no SYNTH domain.
            if ~isfield(NM,'SYNTH'),return;end
            for x=1:numel(NM.SYNTH.analysis)
                A=NM.SYNTH.analysis{x};
                item=struct('index',x,'id',A.id, ...
                    'mode',A.mode,'status',A.status, ...
                    'completed',numel(A.analysisIndices), ...
                    'rootdir',A.rootdir,'rootAvailable',isfolder(A.rootdir));
                if strcmp(A.mode,'fully_synthetic')
                    item.total=size(A.configuration.combinations,1)*A.configuration.plan.NReps;
                    item.nCombinations=size(A.configuration.combinations,1);
                    item.repetitions=A.configuration.plan.NReps;
                else
                    item.total=numel(A.configuration.sampleSizes)*A.configuration.shiftPermutations;
                    item.sampleSizes=num2cell(A.configuration.sampleSizes);
                    item.shiftPermutations=A.configuration.shiftPermutations;
                end
                experiments{end+1}=item; %#ok<AGROW>
            end
        end

        function [handled,out] = handleMatlabService(NM,req,tmpDir,ctx)
            handled=true;
            switch req.operation
                case 'synth_coordinator_initialize'
                    [NM,ok]=NMDataIOUI.loadSessionNM(NM,tmpDir);
                    if ~ok,error('NMSynthCoordinatorUI:session','SYNTH session NM unavailable.');end
                    assert(NMDataIOBrowserModeTools.committedModalityCount(NM)==0, ...
                        'NMSynthCoordinatorUI:nonempty','Placeholder configuration requires an empty NM.');
                    d=req.definition;
                    assert(isequal(sort(fieldnames(d)), ...
                        sort({'modalityNames';'featureCounts';'modeflag';'classCount'})), ...
                        'NMSynthCoordinatorUI:definition','Unexpected SYNTH definition fields.');
                    d=struct('modalityNames',{cellstr(string(d.modalityNames(:)'))}, ...
                        'featureCounts',double(d.featureCounts(:)'), ...
                        'modeflag',char(string(d.modeflag)), ...
                        'classCount',double(d.classCount));
                    assert(numel(d.modalityNames)==numel(d.featureCounts) && ...
                        numel(unique(d.modalityNames))==numel(d.modalityNames) && ...
                        all(d.featureCounts>0 & d.featureCounts==floor(d.featureCounts)) && ...
                        (strcmp(d.modeflag,'classification') && d.classCount>=2 && d.classCount==floor(d.classCount) || ...
                         strcmp(d.modeflag,'regression') && d.classCount==1), ...
                        'NMSynthCoordinatorUI:definition','Invalid modality or target definition.');
                    NM=NMSimulationTools.createSyntheticTemplate(d);
                    NMDataIOUI.saveSessionNM(NM,tmpDir);
                    out=struct('ok',true,'state',NMSynthCoordinatorUI.stateFromNM(NM,ctx));
                case 'synth_coordinator_definition'
                    [NM,ok]=NMDataIOUI.loadSessionNM(NM,tmpDir);
                    if ~ok,error('NMSynthCoordinatorUI:session','SYNTH session NM unavailable.');end
                    definition=NMSimulationTools.syntheticDefinition(NM);
                    definition.featureCounts=num2cell(definition.featureCounts);
                    out=struct('ok',true,'definition',definition);
                case 'synth_coordinator_add_fully'
                    [NM,ok]=NMDataIOUI.loadSessionNM(NM,tmpDir);
                    if ~ok,error('NMSynthCoordinatorUI:session','SYNTH session NM unavailable.');end
                    plan=req.plan;
                    classCount=plan.classCount;
                    plan=rmfield(plan,'classCount');
                    plan.definition=NMSimulationTools.syntheticDefinition(NM);
                    validateattributes(classCount,{'numeric'}, ...
                        {'scalar','finite','integer','positive'});
                    if strcmp(plan.definition.modeflag,'classification')
                        assert(classCount>=2,'NMSynthCoordinatorUI:classCount', ...
                            'Synthetic classification requires at least two groups.');
                    else
                        assert(classCount==1,'NMSynthCoordinatorUI:classCount', ...
                            'Regression has one synthetic outcome.');
                    end
                    plan.definition.classCount=classCount;
                    plan.modalityFactors=num2cell(plan.modalityFactors);
                    [NM,idx]=NMSimulationTools.registerFullySynthetic(NM,plan);
                    NMDataIOUI.saveSessionNM(NM,tmpDir);
                    out=struct('ok',true,'analysisIndex',idx, ...
                        'state',NMSynthCoordinatorUI.stateFromNM(NM,ctx));
                case 'synth_coordinator_refresh'
                    [NM,ok]=NMDataIOUI.loadSessionNM(NM,tmpDir);
                    if ~ok,error('NMSynthCoordinatorUI:session','SYNTH session NM is unavailable.');end
                    NM=NMSimulationTools.reconstructExperiments(NM);
                    NMDataIOUI.saveSessionNM(NM,tmpDir);
                    out=struct('ok',true,'state',NMSynthCoordinatorUI.stateFromNM(NM,ctx));
                case 'synth_coordinator_add'
                    [NM,ok]=NMDataIOUI.loadSessionNM(NM,tmpDir);
                    if ~ok,error('NMSynthCoordinatorUI:session','SYNTH session NM is unavailable.');end
                    % nm2-allow: Only SYNTH placeholder templates include this marker.
                    if isfield(NM,'SYNTH') && isfield(NM.SYNTH,'fullySyntheticDefinition')
                        error('NMSynthCoordinatorUI:placeholder', ...
                            'Configuration placeholders cannot be registered as observed data.');
                    end
                    % Browser ingress configures the established template authority.
                    s=req.synth;
                    [configured,~,report]=NMSynthTools.configure(NM, ...
                        'synthEnabled',true,'synthMethod',s.synthMethod, ...
                        'synthK',s.synthK,'synthDistanceMeasure',s.synthDistanceMeasure, ...
                        'synthStandardizeData',s.synthStandardizeData, ...
                        'synthWrite2Disk',1, ...
                        'synthNComponentsText',s.synthNComponentsText, ...
                        'synthMinMethod',s.synthMinMethod, ...
                        'synthUncertaintyScale',s.synthUncertaintyScale);
                    if ~report.ok,error('NMSynthCoordinatorUI:configuration','%s',strjoin(report.errors,'; '));end
                    [updated,idx]=NMSimulationTools.registerExistingData(configured,req.spec);
                    updated.TrainParam=NM.TrainParam;
                    updated.cv=NM.cv;
                    NMDataIOUI.saveSessionNM(updated,tmpDir);
                    out=struct('ok',true,'analysisIndex',idx, ...
                        'state',NMSynthCoordinatorUI.stateFromNM(updated,ctx));
                case 'synth_coordinator_resume'
                    [NM,ok]=NMDataIOUI.loadSessionNM(NM,tmpDir);
                    if ~ok,error('NMSynthCoordinatorUI:session','SYNTH session NM is unavailable.');end
                    runtimeUI=NMRuntimeProgressTools.emptyUI();
                    if ~isempty(req.progressTaskId)
                        runtimeUI=NMRuntimeProgressTools.browserRuntimeContext( ...
                            tmpDir,req.progressTaskId,struct('source','synth_coordinator', ...
                            'chartEnabled',true,'suppressNativeViewer',true, ...
                            'progressTitle','SYNTH simulation progress'));
                    end
                    try
                        mode=NM.SYNTH.analysis{req.analysisIndex}.mode;
                        if strcmp(mode,'fully_synthetic')
                            assert(islogical(req.parallelEnabled) && isscalar(req.parallelEnabled), ...
                                'NMSynthCoordinatorUI:parallelOption', ...
                                'Parallel execution selection must be true or false.');
                            session=NMSimulationTools.runFullySynthetic(NM,req.analysisIndex,runtimeUI, ...
                                @(updated)NMDataIOUI.saveSessionNM(updated,tmpDir),req.parallelEnabled);
                        else
                            session=NMSimulationTools.runExistingData(NM,req.analysisIndex,runtimeUI, ...
                                @(updated)NMDataIOUI.saveSessionNM(updated,tmpDir));
                        end
                    catch ME
                        NMRuntimeProgressTools.fail(runtimeUI,'SYNTH simulation',ME);
                        rethrow(ME);
                    end
                    out=struct('ok',true,'message',sprintf( ...
                        'Recovered/completed %d SYNTH analyses.',numel(session.runs)), ...
                        'state',NMSynthCoordinatorUI.stateFromNM(session.NM,ctx));
                case 'synth_coordinator_reconstruct'
                    [NM,ok]=NMDataIOUI.loadSessionNM(NM,tmpDir);
                    if ~ok,error('NMSynthCoordinatorUI:session','SYNTH session NM is unavailable.');end
                    runtimeUI=NMRuntimeProgressTools.emptyUI();
                    % Runtime-job requests always carry a progress ID; direct
                    % MATLAB service tests legitimately omit that UI argument.
                    % nm2-allow: S11 direct service operation omits progressTaskId; NMRuntimeJobClient supplies it for active jobs.
                    if isfield(req,'progressTaskId') && ~isempty(req.progressTaskId)
                        runtimeUI=NMRuntimeProgressTools.browserRuntimeContext( ...
                            tmpDir,req.progressTaskId,struct('source','synth_coordinator', ...
                            'chartEnabled',true,'suppressNativeViewer',true, ...
                            'progressTitle','SYNTH reconstruction progress'));
                    end
                    try
                        NM=NMSimulationTools.reconstructExistingData( ...
                            NM,req.analysisIndex,false,runtimeUI);
                    catch ME
                        NMRuntimeProgressTools.fail(runtimeUI,'SYNTH reconstruction',ME);
                        rethrow(ME);
                    end
                    % Refresh restores child membership only. The completion-only
                    % summary remains unchanged; it is never computed by a viewer.
                    NMDataIOUI.saveSessionNM(NM,tmpDir);
                    parent=NM.SYNTH.analysis{req.analysisIndex};
                    if strcmp(parent.mode,'fully_synthetic')
                        parentSynth=NMSynthCoordinatorUI.experimentGeneratorState( ...
                            NMSynthTools.stateFromNM(NM));
                    else
                        parentSynth=NMSynthCoordinatorUI.experimentGeneratorState( ...
                            NMSynthTools.stateFromSynth(parent.configuration.synth));
                    end
                    out=struct('ok',true,'synth',parentSynth, ...
                        'configuration',parent.configuration, ...
                        'state',NMSynthCoordinatorUI.stateFromNM(NM,ctx));
                case 'synth_coordinator_relink_root'
                    [NM,ok]=NMDataIOUI.loadSessionNM(NM,tmpDir);
                    if ~ok,error('NMSynthCoordinatorUI:session','SYNTH session NM is unavailable.');end
                    NM=NMSimulationTools.relinkExperimentRoot(NM, ...
                        req.analysisIndex,req.newRootDir);
                    NMDataIOUI.saveSessionNM(NM,tmpDir);
                    out=struct('ok',true,'state',NMSynthCoordinatorUI.stateFromNM(NM,ctx));
                case 'synth_coordinator_delete'
                    [NM,ok]=NMDataIOUI.loadSessionNM(NM,tmpDir);
                    if ~ok,error('NMSynthCoordinatorUI:session','SYNTH session NM is unavailable.');end
                    NM=NMSimulationTools.reconstructExperiments(NM);
                    parent=NM.SYNTH.analysis{req.analysisIndex};
                    deletedRoot=parent.rootdir;
                    gone=sort(unique(parent.analysisIndices));
                    % Retire this parent before deleting its managed children.
                    % The Analysis Manager alone rebases all surviving indices.
                    NM.SYNTH.analysis(req.analysisIndex)=[];
                    if ~isempty(gone)
                        [NM,~]=NMAnalysisManagerTools.deleteAnalyses(NM,gone,struct('wipe',false));
                    end
                    NMDataIOUI.saveSessionNM(NM,tmpDir);
                    if isfolder(deletedRoot),rmdir(deletedRoot,'s');end
                    out=struct('ok',true,'state',NMSynthCoordinatorUI.stateFromNM(NM,ctx));
                otherwise
                    handled=false;
                    out=struct();
            end
        end

