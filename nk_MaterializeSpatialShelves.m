function [sY, sYocv, sCocv, sAltY, sYw, branchTables] = ...
    nk_MaterializeSpatialShelves(Y, Yocv, Cocv, AltY, inp, spatialPreproc, paramfl, kbin)
% nk_MaterializeSpatialShelves - Materialize canonical subject-spatial shelves.
%
% Purpose
%   This function is the single authority that executes subject-level spatial
%   preprocessing before CV-bound preprocessing. It is shared by precomputed
%   training, on-the-fly training, and trained-model application.
%
% Syntax
%   [sY,sYocv,sCocv,sAltY,sYw,branchTables] = ...
%       nk_MaterializeSpatialShelves(Y,Yocv,Cocv,AltY,inp,spatialPreproc,paramfl,kbin)
%
% Inputs
%   Y, Yocv, Cocv, AltY
%       Raw primary, independent-test, calibration, and alternative data.
%       A cell input represents several parallel data instances. Empty optional
%       inputs are preserved as empty outputs.
%   inp
%       Runtime input state. inp.Yw or inp.iYw may provide an external weighting
%       map; PREPROC-bound external ranking maps are detected by nk_SmoothMask.
%   spatialPreproc
%       Either one PREPROC structure shared by all binary classifiers (candidate
%       materialization), or a kbin-by-1 cell array containing the optimized
%       PREPROC structure for each classifier (application materialization).
%   paramfl
%       Runtime parameters. paramfl.PV must contain the spatial geometry used by
%       nk_PerfSpatialChain and nk_SmoothMask.
%   kbin
%       Number of binary/regression preprocessing containers.
%
% Outputs
%   sY, sYocv, sCocv, sAltY
%       Canonical shelves. For one data instance the contract is
%       shelves{binary}{branch}. For multiple instances it is
%       shelves{binary,instance}{branch}.
%   sYw
%       Canonical weighting-map shelves, sYw{binary}{branch}, or [] when no map
%       is configured.
%   branchTables
%       branchTables{binary}; each table identifies every branch generated by
%       nk_PerfSpatialChain, including its spatial-step parameter values.
%
% Authority and flow
%   This function owns spatial shelf materialization. nk_PerfSpatialChain owns
%   execution of one PREPROC chain; this function owns binary/instance
%   containers, branch-table agreement, and weighting-map shelf alignment.
%   Consumers select from these resident shelves through
%   nk_PerfPreprocessSpatial, reached via nk_ApplyTrainedPreproc.
%
% Scientific/state contract and invariants
%   Every materialized data shelf has exactly one metadata table for its binary
%   classifier. Branch identifiers are contiguous and match shelf order. All
%   parallel data instances and weighting maps must materialize the same branch
%   identity as the primary data. Contract disagreement is an error; branches
%   are never padded, truncated, or inferred from matrix dimensions.
%
% Materialization and performance
%   Spatial operations scan all supplied subjects/features and may invoke SPM
%   image operations. A shared candidate PREPROC is executed once per data
%   instance and the resulting shelf is replicated across binary containers.
%   Binary-specific optimized PREPROC structures are executed once per binary.
%   The function performs no source-file discovery or persistence.
%
% Failure semantics
%   Invalid binary counts, missing geometry, malformed PREPROC containers, or
%   branch/table disagreement raise explicit errors before CV preprocessing.
%
% Side effects
%   None. nk_SmoothMask is invoked on a local copy of inp.
%
% Consumers and dependencies
%   Called by nk_PreprocessPrep, nk_MLOptimizer, nk_PerfInitSpatial, and the raw
%   execution branch of nk_PerfPreprocessSpatial. Depends on
%   nk_PerfSpatialChain and nk_SmoothMask.

if nargin < 8 || isempty(kbin) || ~isscalar(kbin) || kbin < 1 || fix(kbin) ~= kbin
    error('nk_MaterializeSpatialShelves:InvalidBinaryCount', ...
        'kbin must be a positive integer scalar.');
end
if nargin < 7 || ~isstruct(paramfl) || ~isfield(paramfl,'PV') || isempty(paramfl.PV)
    error('nk_MaterializeSpatialShelves:MissingSpatialGeometry', ...
        'paramfl.PV is required for subject-spatial shelf materialization.');
end

[preprocByBinary, sharedPreproc] = normalize_preproc(spatialPreproc, kbin);

branchTables = cell(kbin,1);
[sY, branchTables] = materialize_dataset(Y, preprocByBinary, sharedPreproc, ...
    paramfl.PV, kbin, branchTables, 'training/CV');
[sYocv, branchTables] = materialize_dataset(Yocv, preprocByBinary, sharedPreproc, ...
    paramfl.PV, kbin, branchTables, 'independent-test');
[sCocv, branchTables] = materialize_dataset(Cocv, preprocByBinary, sharedPreproc, ...
    paramfl.PV, kbin, branchTables, 'calibration');
[sAltY, branchTables] = materialize_dataset(AltY, preprocByBinary, sharedPreproc, ...
    paramfl.PV, kbin, branchTables, 'alternative training/CV');

sYw = materialize_weight_shelves(inp, preprocByBinary, paramfl, branchTables, kbin);
end

function [preprocByBinary, sharedPreproc] = normalize_preproc(spatialPreproc, kbin)
if iscell(spatialPreproc)
    if numel(spatialPreproc) ~= kbin
        error('nk_MaterializeSpatialShelves:PreprocBinaryMismatch', ...
            'Expected %g binary-specific PREPROC structures, but received %g.', ...
            kbin, numel(spatialPreproc));
    end
    preprocByBinary = spatialPreproc(:);
    sharedPreproc = false;
else
    if ~isstruct(spatialPreproc) || numel(spatialPreproc) ~= 1
        error('nk_MaterializeSpatialShelves:InvalidPreproc', ...
            'spatialPreproc must be one PREPROC structure or one cell per binary classifier.');
    end
    preprocByBinary = repmat({spatialPreproc}, kbin, 1);
    sharedPreproc = true;
end
for u = 1:kbin
    if ~nk_HasSpatialSteps(preprocByBinary{u})
        error('nk_MaterializeSpatialShelves:MissingSpatialSteps', ...
            'Binary classifier #%g has no subject-spatial preprocessing step.', u);
    end
end
end

function [shelves, branchTables] = materialize_dataset(data, preprocByBinary, ...
    sharedPreproc, PV, kbin, branchTables, dataName)
if isempty(data)
    shelves = [];
    return
end

if iscell(data)
    instances = data(:)';
else
    instances = {data};
end
nInstances = numel(instances);
shelves = cell(kbin,nInstances);

if sharedPreproc
    for n = 1:nInstances
        [shelf, table] = nk_PerfSpatialChain(instances{n}, preprocByBinary{1}, PV);
        validate_shelf(shelf, table, dataName, 1, n);
        branchTables = accept_table(branchTables, table, kbin, dataName, true);
        for u = 1:kbin
            shelves{u,n} = shelf;
        end
    end
else
    for u = 1:kbin
        for n = 1:nInstances
            [shelf, table] = nk_PerfSpatialChain(instances{n}, preprocByBinary{u}, PV);
            validate_shelf(shelf, table, dataName, u, n);
            branchTables = accept_table(branchTables, table, u, dataName, false);
            shelves{u,n} = shelf;
        end
    end
end

if nInstances == 1
    shelves = shelves(:,1);
end
end

function branchTables = accept_table(branchTables, table, target, dataName, shared)
if shared
    indices = 1:target;
else
    indices = target;
end
for u = indices
    if isempty(branchTables{u})
        branchTables{u} = table;
    elseif ~isequaln(branchTables{u}, table)
        error('nk_MaterializeSpatialShelves:BranchIdentityMismatch', ...
            ['The %s data produced a spatial branch table that differs from the ' ...
             'primary shelf for binary classifier #%g.'], dataName, u);
    end
end
end

function validate_shelf(shelf, table, dataName, binaryIndex, instanceIndex)
if ~iscell(shelf) || isempty(shelf)
    error('nk_MaterializeSpatialShelves:InvalidShelf', ...
        'The %s materialization for binary #%g, instance #%g did not return a nonempty branch cell.', ...
        dataName, binaryIndex, instanceIndex);
end
branchIds = unique([table.branch], 'stable');
if numel(branchIds) ~= numel(shelf) || ~isequal(branchIds(:)', 1:numel(shelf))
    error('nk_MaterializeSpatialShelves:InvalidBranchTable', ...
        ['The %s shelf for binary #%g, instance #%g contains %g branches, but ' ...
         'its metadata does not define the same contiguous branch sequence.'], ...
        dataName, binaryIndex, instanceIndex, numel(shelf));
end
end

function sYw = materialize_weight_shelves(inp, preprocByBinary, paramfl, branchTables, kbin)
sYw = cell(kbin,1);
haveInputWeight = (isfield(inp,'Yw') && ~isempty(inp.Yw)) || ...
    (isfield(inp,'iYw') && ~isempty(inp.iYw));
haveWeight = haveInputWeight || has_external_rank_map(preprocByBinary);
if ~haveWeight
    sYw = [];
    return
end

for u = 1:kbin
    workInp = inp;
    if isfield(workInp,'Yw') && isempty(workInp.Yw)
        workInp = rmfield(workInp,'Yw');
    end
    if isfield(workInp,'iYw') && isempty(workInp.iYw)
        workInp = rmfield(workInp,'iYw');
    end
    workInp = nk_SmoothMask(preprocByBinary{u}, workInp, paramfl, u);
    if ~isfield(workInp,'iYw') || isempty(workInp.iYw)
        error('nk_MaterializeSpatialShelves:WeightMaterializationMissing', ...
            'A weighting-map source was configured but no shelf was produced for binary classifier #%g.', u);
    end
    shelf = workInp.iYw;
    if ~iscell(shelf)
        shelf = {shelf};
    end
    expected = numel(unique([branchTables{u}.branch], 'stable'));
    if numel(shelf) ~= expected
        error('nk_MaterializeSpatialShelves:WeightBranchMismatch', ...
            ['The weighting-map shelf for binary classifier #%g contains %g branches; ' ...
             'the data shelf contains %g.'], u, numel(shelf), expected);
    end
    sYw{u} = shelf;
end
end

function tf = has_external_rank_map(preprocByBinary)
tf = false;
for u = 1:numel(preprocByBinary)
    PREPROC = preprocByBinary{u};
    if ~isfield(PREPROC,'ACTPARAM') || isempty(PREPROC.ACTPARAM)
        continue
    end
    for q = 1:numel(PREPROC.ACTPARAM)
        if ~isfield(PREPROC.ACTPARAM{q},'RANK')
            continue
        end
        RANK = PREPROC.ACTPARAM{q}.RANK;
        if isfield(RANK,'algostr') && strcmpi(RANK.algostr,'extern') && ...
                isfield(RANK,'EXTERN') && ~isempty(RANK.EXTERN)
            tf = true;
            return
        end
    end
end
end
